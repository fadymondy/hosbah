package agentproto

import (
	"fmt"
	"strings"
)

// Facts are what an agent reports about its host at enrolment (and system.info refreshes).
type Facts struct {
	Hostname string `json:"hostname"`
	// PrimaryIP is the host's own outbound address. The TCP peer the control plane sees can be a proxy
	// (NPM, Cloudflare), so the server's address comes from here when the agent reports it.
	PrimaryIP     string          `json:"primary_ip,omitempty"`
	OSID          string          `json:"os_id"`      // /etc/os-release ID: ubuntu, debian…
	OSVersion     string          `json:"os_version"` // VERSION_ID: 24.04, 12…
	OSPretty      string          `json:"os_pretty"`
	Arch          string          `json:"arch"` // GOARCH of the running binary: amd64, arm64
	Kernel        string          `json:"kernel"`
	CPUs          int             `json:"cpus"`
	MemTotalBytes uint64          `json:"mem_total_bytes"`
	Systemd       bool            `json:"systemd"`        // PID 1 is systemd
	Virt          string          `json:"virtualization"` // container / vm hint (lxc, docker, kvm…), "" if unknown
	Docker        DockerFacts     `json:"docker"`
	Proxmox       ProxmoxFacts    `json:"proxmox"`
	Ports         map[string]bool `json:"ports"` // port -> free to bind (80, 443, 2019)
	// Services is what already runs on the host (containers, well-known systemd units), so an
	// existing server can be imported with its workloads visible.
	Services []Service `json:"services,omitempty"`
}

// ProxmoxFacts: the host is a Proxmox VE node (pveversion answers).
type ProxmoxFacts struct {
	Installed bool   `json:"installed"`
	Version   string `json:"version,omitempty"`
}

// Service is one workload found on the host.
type Service struct {
	Kind   string   `json:"kind"` // container | systemd | guest
	Name   string   `json:"name"`
	Image  string   `json:"image,omitempty"`
	Status string   `json:"status"`
	Ports  []string `json:"ports,omitempty"`
	// Guests (Proxmox): the details that make each one a site.
	ID        string `json:"id,omitempty"`   // vmid
	Type      string `json:"type,omitempty"` // lxc | qemu
	Address   string `json:"address,omitempty"`
	CPUs      int    `json:"cpus,omitempty"`
	MemBytes  uint64 `json:"mem_bytes,omitempty"`
	DiskBytes uint64 `json:"disk_bytes,omitempty"`
}

// Platform is what Cloudy manages the host as: proxmox (a hypervisor), docker (an engine is
// running) or linux (plain; docker.install will add the engine).
func (f Facts) Platform() string {
	switch {
	case f.Proxmox.Installed:
		return "proxmox"
	case f.Docker.Running:
		return "docker"
	default:
		return "linux"
	}
}

// RHELFamily reports a dnf-based distribution.
func RHELFamily(osID string) bool {
	switch osID {
	case "centos", "rhel", "rocky", "almalinux", "ol", "fedora":
		return true
	}
	return false
}

// DockerFacts is what docker.check and enrolment learn about the Docker engine.
type DockerFacts struct {
	Installed     bool   `json:"installed"`
	Running       bool   `json:"running"`
	Version       string `json:"version,omitempty"`
	StorageDriver string `json:"storage_driver,omitempty"`
	BackingFS     string `json:"backing_fs,omitempty"`
	Error         string `json:"error,omitempty"`
}

// Check is one enrolment check result.
type Check struct {
	Name   string `json:"name"`
	Status string `json:"status"` // pass | warn | fail
	Detail string `json:"detail"`
}

const (
	CheckPass = "pass"
	CheckWarn = "warn"
	CheckFail = "fail"
)

// PortsToCheck are the ports Cloudy's edge will need (Caddy HTTP/HTTPS and its admin API).
var PortsToCheck = []string{"80", "443", "2019"}

// MinMemBytes: the plan's "at least 1 GB RAM". A 1 GB VM reports ~960 MiB after the kernel's
// reservation, so the floor is 900 MiB.
const MinMemBytes = 900 << 20

// EnrollRequest is POST /agent/enroll.
type EnrollRequest struct {
	Token        string  `json:"token"`
	PublicKey    string  `json:"public_key"` // base64 ed25519, generated by the agent; the private half never leaves the host
	AgentVersion string  `json:"agent_version"`
	Facts        Facts   `json:"facts"`
	Checks       []Check `json:"checks"`
}

// EnrollResponse tells the agent who it is and whom to trust.
type EnrollResponse struct {
	ServerID              string  `json:"server_id"`
	ServerName            string  `json:"server_name"`
	ControlPlanePublicKey string  `json:"control_plane_public_key"` // base64 ed25519; pinned, verifies every op
	WebSocketURL          string  `json:"ws_url"`
	Checks                []Check `json:"checks"`
}

// EvaluateChecks turns facts into the enrolment checks. The control plane runs it again on the
// facts it received, so the verdict is the server's, not whatever the agent claimed.
//
// fail = enrolment is refused (Cloudy cannot manage this host); warn = enrolled, with a caveat the
// UI shows.
func EvaluateChecks(f Facts) []Check {
	var out []Check
	add := func(name, status, detail string) {
		out = append(out, Check{Name: name, Status: status, Detail: detail})
	}

	// OS: Ubuntu 22.04 / 24.04 or Debian 12 (the plan's list) and Debian 13 — the owner's
	// Proxmox LXCs are built from debian-13-standard.
	osLabel := strings.TrimSpace(f.OSID + " " + f.OSVersion)
	switch {
	case f.OSID == "ubuntu" && (f.OSVersion == "22.04" || f.OSVersion == "24.04"),
		f.OSID == "debian" && (f.OSVersion == "12" || f.OSVersion == "13"),
		RHELFamily(f.OSID) && f.OSID != "fedora" && (strings.HasPrefix(f.OSVersion, "9") || strings.HasPrefix(f.OSVersion, "10")):
		add("os", CheckPass, osLabel)
	default:
		if osLabel == "" {
			osLabel = "unknown"
		}
		add("os", CheckFail, osLabel+" is not supported — use Ubuntu 22.04/24.04, Debian 12/13 or CentOS Stream/RHEL/Rocky/Alma 9 or 10")
	}

	switch f.Arch {
	case "amd64", "arm64":
		add("arch", CheckPass, f.Arch)
	default:
		add("arch", CheckFail, f.Arch+" is not supported (amd64 or arm64)")
	}

	if f.Systemd {
		add("systemd", CheckPass, "systemd is PID 1 — the agent runs as a service")
	} else {
		add("systemd", CheckWarn, "no systemd — the agent runs detached and will not come back after a reboot")
	}

	mib := f.MemTotalBytes >> 20
	if f.MemTotalBytes >= MinMemBytes {
		add("memory", CheckPass, fmt.Sprintf("%d MiB", mib))
	} else {
		add("memory", CheckFail, fmt.Sprintf("%d MiB — at least 1 GB is required", mib))
	}

	var busy []string
	for _, p := range PortsToCheck {
		if free, ok := f.Ports[p]; ok && !free {
			busy = append(busy, p)
		}
	}
	if len(busy) == 0 {
		add("ports", CheckPass, "80, 443 and 2019 are free")
	} else {
		add("ports", CheckWarn, "in use: "+strings.Join(busy, ", ")+" — Cloudy's Caddy will need them for deploys")
	}

	d := f.Docker
	switch {
	case !d.Installed:
		add("docker", CheckWarn, "Docker is not installed — run the docker.install provisioning step")
	case !d.Running:
		add("docker", CheckWarn, "Docker is installed but the engine is not answering: "+d.Error)
	case d.StorageDriver == "overlay2" || d.StorageDriver == "overlayfs" || d.StorageDriver == "fuse-overlayfs":
		detail := "Docker " + d.Version + ", storage driver " + d.StorageDriver
		if d.BackingFS == "zfs" {
			add("docker", CheckWarn, detail+" on ZFS — needs overlay support on the host (Proxmox LXC on ZFS: use a ZFS 2.2+ host)")
		} else {
			add("docker", CheckPass, detail)
		}
	case d.StorageDriver == "vfs":
		add("docker", CheckWarn, "storage driver vfs — very slow and disk-hungry (typical for Docker in an LXC without overlay support)")
	default:
		add("docker", CheckWarn, "storage driver "+d.StorageDriver+" — overlay2 is the tested one")
	}
	return out
}

// Blocking returns the failed checks (enrolment is refused if there are any).
func Blocking(checks []Check) []Check {
	var out []Check
	for _, c := range checks {
		if c.Status == CheckFail {
			out = append(out, c)
		}
	}
	return out
}
